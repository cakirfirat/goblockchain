function t(key, vars) {
  let s = (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.split('{' + k + '}').join(String(vars[k]));
    }
  }
  return s;
}

function getLang() { return currentLang; }

function i18nLocale() {
  const meta = LANG_META.find((m) => m.code === currentLang);
  return meta ? meta.locale : 'en-US';
}

function setLang(code) {
  if (!I18N[code]) return;
  currentLang = code;
  localStorage.setItem('flatun-lang', code);
  document.documentElement.lang = code;
}

// data-i18n / data-i18n-placeholder / data-i18n-title öznitelikli tüm
// elemanları mevcut dile çevirir (statik metinler)
function applyStaticI18n() {
  for (const el of document.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.getAttribute('data-i18n'));
  }
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  }
  for (const el of document.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.getAttribute('data-i18n-title'));
  }
}

// IPC yanıtındaki hata kodunu yerelleştirilmiş metne çevirir;
// kod bilinmiyorsa main'in Türkçe mesajına, o da yoksa fallback'e düşer.
function errText(res, fallbackKey) {
  if (res && res.code && ERR_CODE_KEYS[res.code]) {
    let msg = t(ERR_CODE_KEYS[res.code]);
    if (res.detail) msg += ': ' + res.detail;
    return msg;
  }
  if (res && res.message) return res.message;
  return t(fallbackKey || 'err.generic');
}
